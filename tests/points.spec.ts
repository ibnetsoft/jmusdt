import { test, expect } from "@playwright/test";

test("mobile keypad preserves exact amounts through review, cancellation, retry and both conversion directions", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  const errors: string[] = [], requests: { direction: string; amount: string; requestKey: string }[] = [];
  page.on("pageerror", e => errors.push(e.message));
  let usdt = 1250123456n, points = 88000000000n;
  const history: { id: string; direction: string; amount: string; created_at: string }[] = [];
  await page.route("**/api/points", async route => {
    if (route.request().method() === "GET") return route.fulfill({ json: { usdt: usdt.toString(), points: points.toString(), debt: "0", history } });
    const body = route.request().postDataJSON();
    requests.push(body);
    if (requests.length === 1) return route.fulfill({ status: 503, json: { error: "전환 실패" } });
    const [whole, fraction = ""] = body.amount.split(".");
    const value = BigInt(whole) * 1000000n + BigInt(fraction.padEnd(6, "0"));
    usdt += body.direction === "usdt_to_points" ? -value : value;
    points += body.direction === "usdt_to_points" ? value : -value;
    history.unshift({ id: crypto.randomUUID(), direction: body.direction, amount: value.toString(), created_at: "2026-10-29T01:00:00Z" });
    return route.fulfill({ json: { id: history[0].id } });
  });
  await page.goto("/points");
  await expect(page.getByRole("button", { name: "전환 내용 확인", exact: true })).toBeDisabled();
  const keypad = page.getByRole("group", { name: "숫자 키패드" });
  for (const value of ["1", "2", "5", "소수점", "1", "2", "3", "4", "5", "6", "7"]) await keypad.getByRole("button", { name: value, exact: true }).click();
  await expect(page.getByLabel("전환 금액", { exact: true })).toHaveValue("125.123456");
  await expect(page.getByLabel("전환 예상 금액")).toHaveText("125.123456 P");
  await page.evaluate(() => scrollTo(0, 0));
  await page.screenshot({ path: "artifacts/points/mobile-dark.png", fullPage: true });
  await page.getByRole("button", { name: "브라이트 모드로 전환" }).click();
  await page.screenshot({ path: "artifacts/points/mobile-light.png", fullPage: true });
  const button = await page.locator(".points-review").boundingBox();
  expect(button!.y + button!.height).toBeLessThanOrEqual(844);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.getByRole("button", { name: "전환 내용 확인", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "전환 최종 확인" })).toBeVisible();
  expect(requests).toHaveLength(0);
  await page.getByRole("button", { name: "취소", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.getByLabel("전환 금액", { exact: true })).toHaveValue("125.123456");
  await page.getByRole("button", { name: "전환 내용 확인", exact: true }).click();
  await page.getByRole("button", { name: "1:1 전환 확정", exact: true }).click();
  await expect(page.getByRole("dialog").getByRole("alert")).toHaveText("전환 실패");
  await page.getByRole("button", { name: "1:1 전환 확정", exact: true }).click();
  await expect(page.getByRole("dialog")).not.toBeVisible();
  await expect(page.getByRole("status").filter({ hasText: "1:1 전환이 완료되었습니다." })).toBeVisible();
  expect(requests).toHaveLength(2);
  expect(requests[1]).toEqual(requests[0]);
  expect(requests[0]).toMatchObject({ direction: "usdt_to_points", amount: "125.123456" });
  expect(requests[0].requestKey).toMatch(/^[0-9a-f-]{36}$/);
  await expect(page.locator(".points-source .points-asset-info p")).toHaveText("잔액 1,125 USDT");
  await expect(page.locator(".points-history-item")).toHaveCount(1);
  await page.getByRole("button", { name: "USDT로 전환", exact: true }).click();
  await page.getByLabel("전환 금액", { exact: true }).fill("0.000001");
  await expect(page.getByLabel("전환 예상 금액")).toHaveText("0.000001 USDT");
  await page.getByRole("button", { name: "전환 내용 확인", exact: true }).click();
  await page.getByRole("button", { name: "1:1 전환 확정", exact: true }).evaluate((button: HTMLButtonElement) => { button.click(); button.click(); });
  await expect(page.locator(".points-history-item")).toHaveCount(2);
  expect(requests).toHaveLength(3);
  expect(requests[2]).toMatchObject({ direction: "points_to_usdt", amount: "0.000001" });
  expect(errors).toEqual([]);
});

test("amount limits, backspace, reversal and insufficient balances prevent invalid conversions", async ({ page }) => {
  let posts = 0;
  await page.route("**/api/points", route => {
    if (route.request().method() === "POST") posts++;
    return route.fulfill({ json: { usdt: "1000000", points: "0", debt: "500000", history: [] } });
  });
  await page.goto("/points");
  const input = page.getByLabel("전환 금액", { exact: true });
  const keypad = page.getByRole("group", { name: "숫자 키패드" });
  await keypad.getByRole("button", { name: "소수점", exact: true }).click();
  await expect(input).toHaveValue("0.");
  await keypad.getByRole("button", { name: "1", exact: true }).click();
  await expect(input).toHaveValue("0.1");
  await keypad.getByRole("button", { name: "마지막 숫자 지우기", exact: true }).click();
  await expect(input).toHaveValue("0.");
  await input.fill("2");
  await expect(page.getByRole("alert").filter({ hasText: "전환할 잔액이 부족합니다." })).toBeVisible();
  await expect(page.getByRole("button", { name: "전환 내용 확인", exact: true })).toBeDisabled();
  await input.fill("1");
  await page.getByRole("button", { name: "전환 방향 바꾸기" }).click();
  await expect(page.getByRole("button", { name: "USDT로 전환", exact: true })).toHaveAttribute("aria-pressed", "true");
  await expect(page.getByRole("button", { name: "전환 내용 확인", exact: true })).toBeDisabled();
  await page.getByRole("button", { name: "전환 방향 바꾸기" }).click();
  await input.fill("0000000.123456");
  await expect(input).toHaveValue("0.123456");
  await keypad.getByRole("button", { name: "7", exact: true }).click();
  await expect(input).toHaveValue("0.123456");
  await input.fill("9999999999");
  await keypad.getByRole("button", { name: "9", exact: true }).click();
  await expect(input).toHaveValue("9999999999");
  await input.fill("0.5");
  await page.getByRole("button", { name: "전환 내용 확인", exact: true }).click();
  await expect(page.getByRole("dialog").getByText(/미수금이 우선 상계/)).toBeVisible();
  await page.keyboard.press("Escape");
  await expect(page.getByRole("dialog")).not.toBeVisible();
  expect(posts).toBe(0);
});

test("reference layout stays usable in both themes, three languages and narrow or desktop viewports", async ({ page }) => {
  await page.route("**/api/points", route => route.fulfill({ json: { usdt: "9999999999999999", points: "88000000000", debt: "0", history: [] } }));
  await page.setViewportSize({ width: 320, height: 740 });
  await page.goto("/points");
  await page.getByLabel("전환 금액", { exact: true }).fill("9999999999.999999");
  for (const locale of ["ko", "en", "ja"]) {
    await page.locator(".site-controls select").selectOption(locale);
    await expect(page.locator("html")).toHaveAttribute("lang", locale);
    await expect(page.locator(".points-source input")).toHaveValue("9999999999.999999");
    expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
    expect(await page.locator(".points-keypad button").count()).toBe(12);
  }
  await expect(page.getByRole("button", { name: "ポイントに交換", exact: true })).toBeVisible();
  await expect(page.getByLabel("交換予定額")).toHaveText("9,999,999,999.999999 P");
  await page.screenshot({ path: "artifacts/points/mobile-ja-narrow.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator(".site-controls select").selectOption("en");
  await expect(page.getByRole("heading", { name: "Point conversion", exact: true })).toBeVisible();
  await page.getByLabel("Conversion amount", { exact: true }).fill("250");
  await page.screenshot({ path: "artifacts/points/desktop-en.png", fullPage: true });
  const cards = await page.locator(".points-assets").boundingBox();
  expect(cards!.width).toBeLessThanOrEqual(560);
  expect(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
});
